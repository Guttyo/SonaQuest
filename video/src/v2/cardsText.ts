export type StatCard = {
  /** カウントアップで数える値と、表示の小数の桁 */
  value: number;
  decimals: number;
  unit: string;
  /** 何の数か */
  label: string;
  /** ひとことの言い換え（無ければ出さない） */
  sub?: string;
  /** 条件 */
  note: string;
  /** カードごとの出典（まとめて下に出すときは空） */
  source?: string;
  /** 出す時刻（秒） */
  at: number;
};

export type StatsSet = {
  kind: "stats";
  /** カードの上に出す前置き（「ある調査では」など） */
  lead?: string;
  cards: StatCard[];
  /** 下にまとめて出す出典と条件 */
  footnote?: string;
};

export type SourceQuoteSet = {
  kind: "sourceQuote";
  /** 引用の上の、何の資料のどこかの説明 */
  heading: string;
  /** 資料の文（文字どおり） */
  quote: string;
  source: string;
  quoteAt: number;
  /**
   * 引用とは別に出す文（資料には書かれていない、動画の説明）。出典を付けず、引用と見た目を分ける。
   * 2026-11-12 オーナー決定「案4にする」の「通信が止まれば、この仕組みも使えません」
   */
  statements: Array<{ at: number; text: string }>;
};

